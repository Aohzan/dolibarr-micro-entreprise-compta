/** Last day included in the seed: payments after it are not recorded. */
const SEED_TODAY = '2026-11-10';

/** First and last years with invoices. */
const SEED_FIRST_YEAR = 2023;
const SEED_LAST_YEAR = 2026;

/**
 * Stop the seed with a message.
 *
 * @param string $message What failed
 * @param object|null $object Dolibarr object holding the error
 * @return never
 */
function seedFail($message, $object = null)
{
	$detail = $object ? ' '.$object->error.' '.implode(', ', (array) $object->errors) : '';
	fwrite(STDERR, 'Seed failed: '.$message.$detail.PHP_EOL);
	exit(1);
}

/**
 * Turn a Y-m-d date into a Dolibarr timestamp at noon.
 *
 * @param string $date Date as Y-m-d
 * @return int
 */
function seedDate($date)
{
	list($y, $m, $d) = array_map('intval', explode('-', $date));
	return dol_mktime(12, 0, 0, $m, $d, $y);
}

$db->begin();

$user = new User($db);
if ($user->fetch(0, 'admin') <= 0) {
	seedFail('admin user not found', $user);
}
$user->loadRights();

// Micro-entreprises are usually under the VAT franchise.
dolibarr_set_const($db, 'FACTURE_TVAOPTION', 0, 'chaine', 0, '', $conf->entity);

$paymentTypeId = dol_getIdFromCode($db, 'VIR', 'c_paiement', 'code', 'id', 1);

$customers = array();
foreach (array('Atelier Dupont', 'Studio Lumière', 'Boulangerie Martin') as $name) {
	$soc = new Societe($db);
	$soc->name = $name;
	$soc->client = 1;
	$soc->code_client = '-1'; // generated by the numbering module
	$soc->country_id = 1;
	if ($soc->create($user) <= 0) {
		seedFail('customer '.$name, $soc);
	}
	$customers[] = $soc->id;
}

$catalog = array(
	array('ref' => 'DEV-DAY', 'label' => 'Développement (jour)', 'type' => Product::TYPE_SERVICE, 'price' => 450),
	array('ref' => 'TRAINING', 'label' => 'Formation (demi-journée)', 'type' => Product::TYPE_SERVICE, 'price' => 320),
	array('ref' => 'BOOK', 'label' => 'Livre « Bien démarrer »', 'type' => Product::TYPE_PRODUCT, 'price' => 25),
);
$products = array();
foreach ($catalog as $item) {
	$product = new Product($db);
	$product->ref = $item['ref'];
	$product->label = $item['label'];
	$product->type = $item['type'];
	$product->price = $item['price'];
	$product->price_base_type = 'HT';
	$product->tva_tx = 0;
	$product->status = 1;
	$product->status_buy = 0;
	if ($product->create($user) <= 0) {
		seedFail('product '.$item['ref'], $product);
	}
	$item['id'] = $product->id;
	$products[] = $item;
}

/**
 * Record a payment on an invoice.
 *
 * @param DoliDB $db Database handler
 * @param User $user Acting user
 * @param Facture $invoice Validated invoice
 * @param float $amount Amount received
 * @param int $date Payment timestamp
 * @param int $paymentTypeId Payment mode id
 * @return void
 */
function seedPayment($db, $user, $invoice, $amount, $date, $paymentTypeId)
{
	$payment = new Paiement($db);
	$payment->datepaye = $date;
	$payment->amounts = array($invoice->id => price2num($amount, 'MT'));
	$payment->paiementid = $paymentTypeId;
	$payment->num_payment = '';
	if ($payment->create($user, 1) <= 0) {
		seedFail('payment of '.$invoice->ref, $payment);
	}
}

mt_srand(42);
$today = seedDate(SEED_TODAY);
$invoiceCount = 0;

for ($year = SEED_FIRST_YEAR; $year <= SEED_LAST_YEAR; $year++) {
	for ($month = 1; $month <= 12; $month++) {
		// Activity grows a little each year and slows down in August.
		$nb = ($month == 8) ? 1 : 2 + mt_rand(0, 1 + ($year - SEED_FIRST_YEAR));
		for ($n = 0; $n < $nb; $n++) {
			$invoiceDate = dol_mktime(12, 0, 0, $month, mt_rand(1, 28), $year);
			if ($invoiceDate > $today) {
				break 3;
			}

			$invoice = new Facture($db);
			$invoice->socid = $customers[mt_rand(0, count($customers) - 1)];
			$invoice->type = Facture::TYPE_STANDARD;
			$invoice->date = $invoiceDate;
			$invoice->cond_reglement_id = 1;
			$invoice->mode_reglement_id = $paymentTypeId;
			if ($invoice->create($user) <= 0) {
				seedFail('invoice', $invoice);
			}

			// One or two service lines, sometimes a few books.
			$service = $products[mt_rand(0, 1)];
			$invoice->addline($service['label'], $service['price'], mt_rand(1, 4), 0, 0, 0, $service['id'], 0, '', '', 0, 0, 0, 'HT', 0, $service['type']);
			if (mt_rand(0, 3) == 0) {
				$book = $products[2];
				$invoice->addline($book['label'], $book['price'], mt_rand(2, 10), 0, 0, 0, $book['id'], 0, '', '', 0, 0, 0, 'HT', 0, $book['type']);
			}
			if ($invoice->validate($user) <= 0) {
				seedFail('validation of invoice', $invoice);
			}
			$invoice->fetch($invoice->id);
			$invoiceCount++;

			$total = (float) $invoice->total_ttc;
			$paidOn = $invoiceDate + mt_rand(0, 45) * 86400;
			if ($paidOn > $today) {
				continue; // still unpaid
			}

			if (mt_rand(0, 9) == 0) {
				// Deposit now, balance a month later: a partial payment.
				$deposit = round($total * 0.3, 2);
				seedPayment($db, $user, $invoice, $deposit, $paidOn, $paymentTypeId);
				$balanceOn = $paidOn + 30 * 86400;
				if ($balanceOn <= $today) {
					seedPayment($db, $user, $invoice, $total - $deposit, $balanceOn, $paymentTypeId);
					$invoice->setPaid($user);
				}
			} else {
				seedPayment($db, $user, $invoice, $total, $paidOn, $paymentTypeId);
				$invoice->setPaid($user);
			}
		}
	}
}

// Contribution rates in the module's current storage format:
// rate = first.second, "second" holding "accuracy" digits; level 0 marks a year.
$rates = array(
	// year => array(level, type (0 products, 1 services, 2 both), name, first, second)
	2023 => array(array(1, 1, 'Cotisations sociales BNC', 21, 10), array(1, 0, 'Cotisations sociales ventes', 12, 30), array(3, 2, 'CFP', 0, 20)),
	2024 => array(array(1, 1, 'Cotisations sociales BNC', 23, 10), array(1, 0, 'Cotisations sociales ventes', 12, 30), array(3, 2, 'CFP', 0, 20)),
	2025 => array(array(1, 1, 'Cotisations sociales BNC', 24, 60), array(1, 0, 'Cotisations sociales ventes', 12, 30), array(3, 2, 'CFP', 0, 20)),
	2026 => array(array(1, 1, 'Cotisations sociales BNC', 25, 60), array(1, 0, 'Cotisations sociales ventes', 12, 30), array(3, 2, 'CFP', 0, 20)),
);
foreach ($rates as $year => $lines) {
	$db->query('INSERT INTO '.MAIN_DB_PREFIX."ame_rates (name, level, year, type) VALUES ('AME_UPDATE', 0, ".((int) $year).', 0)');
	foreach ($lines as $line) {
		list($level, $type, $name, $first, $second) = $line;
		$sql = 'INSERT INTO '.MAIN_DB_PREFIX.'ame_rates (name, level, year, type, accuracy, first, second)';
		$sql .= " VALUES ('".$db->escape($name)."', ".((int) $level).', '.((int) $year).', '.((int) $type).', 2, '.((int) $first).', '.((int) $second).')';
		if (!$db->query($sql)) {
			seedFail('rate '.$name.' '.$year.' '.$db->lasterror());
		}
	}
}

$db->commit();
print 'Seeded '.$invoiceCount.' invoices.'.PHP_EOL;
