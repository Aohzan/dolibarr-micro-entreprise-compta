/**
 * Seed a fresh Dolibarr with fictitious micro-entreprise data.
 *
 * Run once by the dolibarr/dolibarr image on first boot (docker-init.d).
 * The data is deterministic (fixed random seed and fixed "today"), so the
 * end-to-end tests can assert exact amounts.
 */

if (PHP_SAPI !== 'cli') {
	exit(1);
}

define('NOSESSION', 1);
define('NOREQUIREUSER', 1);
define('NOREQUIRETRAN', 1);

require '/var/www/html/master.inc.php';
require_once DOL_DOCUMENT_ROOT.'/core/lib/admin.lib.php';
require_once DOL_DOCUMENT_ROOT.'/user/class/user.class.php';
require_once DOL_DOCUMENT_ROOT.'/societe/class/societe.class.php';
